IF OBJECT_ID('dbo.g_emp','U') IS NULL CREATE TABLE dbo.g_emp(
 GECODEMP DECIMAL(10,0) NOT NULL PRIMARY KEY, GERAZSOC VARCHAR(100) NOT NULL,
 GerazSMS VARCHAR(60) NULL, GEgiro1 VARCHAR(100) NULL, GEgiro2 VARCHAR(100) NULL,
 GEfonNum VARCHAR(30) NULL, GErut DECIMAL(9,0) NULL, GEDv CHAR(1) NULL,
 GEdire VARCHAR(120) NULL, GEregion VARCHAR(50) NULL, GEciudad VARCHAR(50) NULL,
 GeComuna VARCHAR(50) NULL, GeCordinador VARCHAR(80) NULL, geCorreo VARCHAR(120) NULL,
 GeEstado INT NOT NULL DEFAULT(1), GeLogo VARBINARY(MAX) NULL, GePaginaWeb VARCHAR(150) NULL,
 GeFecContIni DATE NULL, GeFecContFin DATE NULL);

IF OBJECT_ID('dbo.USUARIOS','U') IS NULL CREATE TABLE dbo.USUARIOS(
 GECODEMP DECIMAL(10,0) NOT NULL, UsuLogin VARCHAR(10) NOT NULL, UsuClave VARCHAR(10) NULL,
 UsuRut INT NULL, UsuDV CHAR(1) NULL, Usunom VARCHAR(35) NOT NULL, UsuCargo VARCHAR(30) NULL,
 usucrea VARCHAR(10) NULL, UsuCorreo VARCHAR(80) NOT NULL, UsuEstado INT NOT NULL DEFAULT(1),
 UsuPerfil VARCHAR(10) NULL, UsuTipo INT NOT NULL DEFAULT(0), UsuNseg INT NOT NULL DEFAULT(0),
 usuFecCrea DATETIME2(0) NOT NULL DEFAULT(SYSUTCDATETIME()), PRIMARY KEY(GECODEMP,UsuLogin),
 FOREIGN KEY(GECODEMP) REFERENCES dbo.g_emp(GECODEMP));
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.USUARIOS') AND name='UX_USUARIOS_HOTEL_EMAIL') CREATE UNIQUE INDEX UX_USUARIOS_HOTEL_EMAIL ON dbo.USUARIOS(GECODEMP,UsuCorreo);

IF OBJECT_ID('dbo.SEGUSUCRED','U') IS NULL CREATE TABLE dbo.SEGUSUCRED(
 GECODEMP DECIMAL(10,0) NOT NULL, UsuLogin VARCHAR(10) NOT NULL, PasswordSalt VARCHAR(64) NOT NULL,
 PasswordHash VARCHAR(256) NOT NULL, MigradoDesdeGX BIT NOT NULL DEFAULT(0), FechaCambio DATETIME2(0) NOT NULL DEFAULT(SYSUTCDATETIME()),
 PRIMARY KEY(GECODEMP,UsuLogin), FOREIGN KEY(GECODEMP,UsuLogin) REFERENCES dbo.USUARIOS(GECODEMP,UsuLogin));
IF OBJECT_ID('dbo.SEGSESION','U') IS NULL CREATE TABLE dbo.SEGSESION(
 TokenHash CHAR(64) NOT NULL PRIMARY KEY, GECODEMP DECIMAL(10,0) NOT NULL, UsuLogin VARCHAR(10) NOT NULL,
 FechaCreacion DATETIME2(0) NOT NULL DEFAULT(SYSUTCDATETIME()), FechaExpiracion DATETIME2(0) NOT NULL,
 UltimoUso DATETIME2(0) NULL, Revocada BIT NOT NULL DEFAULT(0), FOREIGN KEY(GECODEMP,UsuLogin) REFERENCES dbo.USUARIOS(GECODEMP,UsuLogin));

IF OBJECT_ID('dbo.UROLES','U') IS NULL CREATE TABLE dbo.UROLES(ROLCod VARCHAR(10) NOT NULL PRIMARY KEY,ROLNombre VARCHAR(30) NOT NULL,ROLFCrea DATETIME2(0) NULL,ROLUCrea VARCHAR(10) NULL);
IF OBJECT_ID('dbo.URolesPorUser','U') IS NULL CREATE TABLE dbo.URolesPorUser(GECODEMP DECIMAL(10,0) NOT NULL,UsuLogin VARCHAR(10) NOT NULL,ROLCod VARCHAR(10) NOT NULL,RXUFecCrea DATETIME2(0) NULL,PRIMARY KEY(GECODEMP,UsuLogin,ROLCod));
IF OBJECT_ID('dbo.SISTEMAS','U') IS NULL CREATE TABLE dbo.SISTEMAS(SistCod INT NOT NULL PRIMARY KEY,SistNombre VARCHAR(40) NOT NULL,SistFecCrea DATE NULL,SistFAIcons VARCHAR(30) NULL);
IF OBJECT_ID('dbo.MODULOS','U') IS NULL CREATE TABLE dbo.MODULOS(SistCod INT NOT NULL,Modcod INT NOT NULL,ModTipo INT NOT NULL,Modprg VARCHAR(15) NULL,ModDes VARCHAR(30) NOT NULL,ModFcrea DATE NULL,ModFAIcons VARCHAR(30) NULL,PRIMARY KEY(SistCod,Modcod));
IF OBJECT_ID('dbo.PROGRAM','U') IS NULL CREATE TABLE dbo.PROGRAM(SistCod INT NOT NULL,Modcod INT NOT NULL,ProgCod INT NOT NULL,ProgDes VARCHAR(35) NOT NULL,ProgFcrea DATE NULL,ProgTipo INT NOT NULL,ProgNomGX VARCHAR(100) NULL,ProgIDmenu VARCHAR(20) NULL,ProgTarget VARCHAR(20) NULL,PRIMARY KEY(SistCod,Modcod,ProgCod));
IF OBJECT_ID('dbo.PROGRAM1','U') IS NULL CREATE TABLE dbo.PROGRAM1(SistCod INT NOT NULL,Modcod INT NOT NULL,ProgCod INT NOT NULL,ProgOPCod INT NOT NULL,ProgOPDes VARCHAR(35) NOT NULL,PRIMARY KEY(SistCod,Modcod,ProgCod,ProgOPCod));
IF OBJECT_ID('dbo.ASIGSIST','U') IS NULL CREATE TABLE dbo.ASIGSIST(GECODEMP DECIMAL(10,0) NOT NULL,AsgSisLogin VARCHAR(10) NOT NULL,SistCod INT NOT NULL,PRIMARY KEY(GECODEMP,AsgSisLogin,SistCod));
IF OBJECT_ID('dbo.ASIG','U') IS NULL CREATE TABLE dbo.ASIG(GECODEMP DECIMAL(10,0) NOT NULL,AsigUsu VARCHAR(10) NOT NULL,SistCod INT NOT NULL,AsigMod INT NOT NULL,AsigAsig VARCHAR(10) NULL,PRIMARY KEY(GECODEMP,AsigUsu,SistCod,AsigMod));
IF OBJECT_ID('dbo.ASIGPROG','U') IS NULL CREATE TABLE dbo.ASIGPROG(GECODEMP DECIMAL(10,0) NOT NULL,UsuLogin VARCHAR(10) NOT NULL,SistCod INT NOT NULL,Modcod INT NOT NULL,ProgCod INT NOT NULL,ProgUsuC VARCHAR(10) NULL,PRIMARY KEY(GECODEMP,UsuLogin,SistCod,Modcod,ProgCod));
IF OBJECT_ID('dbo.ASIGPROG1','U') IS NULL CREATE TABLE dbo.ASIGPROG1(GECODEMP DECIMAL(10,0) NOT NULL,UsuLogin VARCHAR(10) NOT NULL,SistCod INT NOT NULL,Modcod INT NOT NULL,ProgCod INT NOT NULL,ProgOPCod INT NOT NULL,PRIMARY KEY(GECODEMP,UsuLogin,SistCod,Modcod,ProgCod,ProgOPCod));
IF OBJECT_ID('dbo.NIVSEG','U') IS NULL CREATE TABLE dbo.NIVSEG(GECODEMP DECIMAL(10,0) NOT NULL,UsuLogin VARCHAR(10) NOT NULL,NivSeg INT NOT NULL DEFAULT(0),PRIMARY KEY(GECODEMP,UsuLogin));
