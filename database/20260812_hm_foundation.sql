/*
  HM Hotel Manager - operational foundation
  Each g_emp company is one hotel. GECODEMP is the tenant boundary and is
  included in every primary key and foreign key to prevent cross-hotel links.
*/

SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.HMLOCATION', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.HMLOCATION (
    GECODEMP DECIMAL(10, 0) NOT NULL,
    LocationId BIGINT IDENTITY(1, 1) NOT NULL,
    ParentLocationId BIGINT NULL,
    LocationType VARCHAR(30) NOT NULL,
    LocationCode VARCHAR(50) NULL,
    LocationName NVARCHAR(120) NOT NULL,
    FloorLabel NVARCHAR(30) NULL,
    IsActive BIT NOT NULL CONSTRAINT DF_HMLOCATION_IsActive DEFAULT (1),
    CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMLOCATION_CreatedAt DEFAULT (SYSUTCDATETIME()),
    UpdatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMLOCATION_UpdatedAt DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_HMLOCATION PRIMARY KEY (GECODEMP, LocationId),
    CONSTRAINT UQ_HMLOCATION_Code UNIQUE (GECODEMP, LocationCode),
    CONSTRAINT CK_HMLOCATION_Type CHECK (LocationType IN ('BUILDING', 'FLOOR', 'ROOM', 'AREA', 'EQUIPMENT_ROOM')),
    CONSTRAINT FK_HMLOCATION_Hotel FOREIGN KEY (GECODEMP) REFERENCES dbo.g_emp(GECODEMP),
    CONSTRAINT FK_HMLOCATION_Parent FOREIGN KEY (GECODEMP, ParentLocationId)
      REFERENCES dbo.HMLOCATION(GECODEMP, LocationId)
  );
END;

IF OBJECT_ID('dbo.HMCATEGORY', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.HMCATEGORY (
    GECODEMP DECIMAL(10, 0) NOT NULL,
    CategoryId BIGINT IDENTITY(1, 1) NOT NULL,
    CategoryName NVARCHAR(80) NOT NULL,
    IconName VARCHAR(60) NULL,
    ColourCode CHAR(7) NULL,
    DefaultPriority VARCHAR(10) NOT NULL CONSTRAINT DF_HMCATEGORY_DefaultPriority DEFAULT ('NORMAL'),
    IsActive BIT NOT NULL CONSTRAINT DF_HMCATEGORY_IsActive DEFAULT (1),
    CONSTRAINT PK_HMCATEGORY PRIMARY KEY (GECODEMP, CategoryId),
    CONSTRAINT UQ_HMCATEGORY_Name UNIQUE (GECODEMP, CategoryName),
    CONSTRAINT CK_HMCATEGORY_Priority CHECK (DefaultPriority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT FK_HMCATEGORY_Hotel FOREIGN KEY (GECODEMP) REFERENCES dbo.g_emp(GECODEMP)
  );
END;

IF OBJECT_ID('dbo.HMASSET', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.HMASSET (
    GECODEMP DECIMAL(10, 0) NOT NULL,
    AssetId BIGINT IDENTITY(1, 1) NOT NULL,
    LocationId BIGINT NULL,
    CategoryId BIGINT NULL,
    AssetTag VARCHAR(50) NOT NULL,
    AssetName NVARCHAR(120) NOT NULL,
    Manufacturer NVARCHAR(80) NULL,
    Model NVARCHAR(80) NULL,
    SerialNumber NVARCHAR(100) NULL,
    AssetStatus VARCHAR(20) NOT NULL CONSTRAINT DF_HMASSET_Status DEFAULT ('ACTIVE'),
    IsActive BIT NOT NULL CONSTRAINT DF_HMASSET_IsActive DEFAULT (1),
    CONSTRAINT PK_HMASSET PRIMARY KEY (GECODEMP, AssetId),
    CONSTRAINT UQ_HMASSET_Tag UNIQUE (GECODEMP, AssetTag),
    CONSTRAINT CK_HMASSET_Status CHECK (AssetStatus IN ('ACTIVE', 'OUT_OF_SERVICE', 'RETIRED')),
    CONSTRAINT FK_HMASSET_Hotel FOREIGN KEY (GECODEMP) REFERENCES dbo.g_emp(GECODEMP),
    CONSTRAINT FK_HMASSET_Location FOREIGN KEY (GECODEMP, LocationId) REFERENCES dbo.HMLOCATION(GECODEMP, LocationId),
    CONSTRAINT FK_HMASSET_Category FOREIGN KEY (GECODEMP, CategoryId) REFERENCES dbo.HMCATEGORY(GECODEMP, CategoryId)
  );
END;

IF OBJECT_ID('dbo.HMWORKORDER', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.HMWORKORDER (
    GECODEMP DECIMAL(10, 0) NOT NULL,
    WorkOrderId BIGINT IDENTITY(1, 1) NOT NULL,
    WorkOrderNumber INT NOT NULL,
    LocationId BIGINT NULL,
    AssetId BIGINT NULL,
    CategoryId BIGINT NULL,
    Title NVARCHAR(160) NOT NULL,
    Description NVARCHAR(MAX) NULL,
    Priority VARCHAR(10) NOT NULL CONSTRAINT DF_HMWORKORDER_Priority DEFAULT ('NORMAL'),
    Status VARCHAR(20) NOT NULL CONSTRAINT DF_HMWORKORDER_Status DEFAULT ('NEW'),
    ReportedByLogin VARCHAR(10) NOT NULL,
    AssignedToLogin VARCHAR(10) NULL,
    DueAt DATETIME2(0) NULL,
    StartedAt DATETIME2(0) NULL,
    CompletedAt DATETIME2(0) NULL,
    CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMWORKORDER_CreatedAt DEFAULT (SYSUTCDATETIME()),
    UpdatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMWORKORDER_UpdatedAt DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_HMWORKORDER PRIMARY KEY (GECODEMP, WorkOrderId),
    CONSTRAINT UQ_HMWORKORDER_Number UNIQUE (GECODEMP, WorkOrderNumber),
    CONSTRAINT CK_HMWORKORDER_Priority CHECK (Priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT CK_HMWORKORDER_Status CHECK (Status IN ('NEW', 'ASSIGNED', 'IN_PROGRESS', 'ON_HOLD', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT FK_HMWORKORDER_Hotel FOREIGN KEY (GECODEMP) REFERENCES dbo.g_emp(GECODEMP),
    CONSTRAINT FK_HMWORKORDER_Location FOREIGN KEY (GECODEMP, LocationId) REFERENCES dbo.HMLOCATION(GECODEMP, LocationId),
    CONSTRAINT FK_HMWORKORDER_Asset FOREIGN KEY (GECODEMP, AssetId) REFERENCES dbo.HMASSET(GECODEMP, AssetId),
    CONSTRAINT FK_HMWORKORDER_Category FOREIGN KEY (GECODEMP, CategoryId) REFERENCES dbo.HMCATEGORY(GECODEMP, CategoryId)
  );
END;

IF OBJECT_ID('dbo.HMWORKORDERASSIGNMENT', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.HMWORKORDERASSIGNMENT (
    GECODEMP DECIMAL(10, 0) NOT NULL,
    AssignmentId BIGINT IDENTITY(1, 1) NOT NULL,
    WorkOrderId BIGINT NOT NULL,
    TechnicianLogin VARCHAR(10) NOT NULL,
    AssignedByLogin VARCHAR(10) NOT NULL,
    AssignedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMWORKORDERASSIGNMENT_AssignedAt DEFAULT (SYSUTCDATETIME()),
    UnassignedAt DATETIME2(0) NULL,
    CONSTRAINT PK_HMWORKORDERASSIGNMENT PRIMARY KEY (GECODEMP, AssignmentId),
    CONSTRAINT FK_HMWORKORDERASSIGNMENT_Order FOREIGN KEY (GECODEMP, WorkOrderId)
      REFERENCES dbo.HMWORKORDER(GECODEMP, WorkOrderId)
  );
END;

IF OBJECT_ID('dbo.HMWORKORDEREVENT', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.HMWORKORDEREVENT (
    GECODEMP DECIMAL(10, 0) NOT NULL,
    EventId BIGINT IDENTITY(1, 1) NOT NULL,
    WorkOrderId BIGINT NOT NULL,
    EventType VARCHAR(30) NOT NULL,
    PerformedByLogin VARCHAR(10) NOT NULL,
    PreviousValue NVARCHAR(MAX) NULL,
    NewValue NVARCHAR(MAX) NULL,
    Details NVARCHAR(1000) NULL,
    OccurredAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMWORKORDEREVENT_OccurredAt DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_HMWORKORDEREVENT PRIMARY KEY (GECODEMP, EventId),
    CONSTRAINT CK_HMWORKORDEREVENT_Type CHECK (EventType IN ('CREATED', 'STATUS_CHANGED', 'PRIORITY_CHANGED', 'ASSIGNED', 'UNASSIGNED', 'COMMENTED', 'ATTACHMENT_ADDED')),
    CONSTRAINT FK_HMWORKORDEREVENT_Order FOREIGN KEY (GECODEMP, WorkOrderId)
      REFERENCES dbo.HMWORKORDER(GECODEMP, WorkOrderId)
  );
END;

IF OBJECT_ID('dbo.HMWORKORDERCOMMENT', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.HMWORKORDERCOMMENT (
    GECODEMP DECIMAL(10, 0) NOT NULL,
    CommentId BIGINT IDENTITY(1, 1) NOT NULL,
    WorkOrderId BIGINT NOT NULL,
    AuthorLogin VARCHAR(10) NOT NULL,
    CommentBody NVARCHAR(2000) NOT NULL,
    CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMWORKORDERCOMMENT_CreatedAt DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_HMWORKORDERCOMMENT PRIMARY KEY (GECODEMP, CommentId),
    CONSTRAINT FK_HMWORKORDERCOMMENT_Order FOREIGN KEY (GECODEMP, WorkOrderId)
      REFERENCES dbo.HMWORKORDER(GECODEMP, WorkOrderId)
  );
END;

IF OBJECT_ID('dbo.HMWORKORDERATTACHMENT', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.HMWORKORDERATTACHMENT (
    GECODEMP DECIMAL(10, 0) NOT NULL,
    AttachmentId BIGINT IDENTITY(1, 1) NOT NULL,
    WorkOrderId BIGINT NOT NULL,
    EventId BIGINT NULL,
    AttachmentKind VARCHAR(20) NOT NULL,
    StorageKey NVARCHAR(500) NOT NULL,
    OriginalFileName NVARCHAR(255) NOT NULL,
    MimeType VARCHAR(100) NOT NULL,
    FileSizeBytes BIGINT NOT NULL,
    UploadedByLogin VARCHAR(10) NOT NULL,
    CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMWORKORDERATTACHMENT_CreatedAt DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_HMWORKORDERATTACHMENT PRIMARY KEY (GECODEMP, AttachmentId),
    CONSTRAINT CK_HMWORKORDERATTACHMENT_Kind CHECK (AttachmentKind IN ('PHOTO', 'RECEIPT', 'DOCUMENT')),
    CONSTRAINT CK_HMWORKORDERATTACHMENT_Size CHECK (FileSizeBytes > 0),
    CONSTRAINT FK_HMWORKORDERATTACHMENT_Order FOREIGN KEY (GECODEMP, WorkOrderId)
      REFERENCES dbo.HMWORKORDER(GECODEMP, WorkOrderId),
    CONSTRAINT FK_HMWORKORDERATTACHMENT_Event FOREIGN KEY (GECODEMP, EventId)
      REFERENCES dbo.HMWORKORDEREVENT(GECODEMP, EventId)
  );
END;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.HMLOCATION') AND name = 'IX_HMLOCATION_Parent')
  CREATE INDEX IX_HMLOCATION_Parent ON dbo.HMLOCATION(GECODEMP, ParentLocationId) WHERE ParentLocationId IS NOT NULL;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.HMWORKORDER') AND name = 'IX_HMWORKORDER_Queue')
  CREATE INDEX IX_HMWORKORDER_Queue ON dbo.HMWORKORDER(GECODEMP, Status, Priority, DueAt);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.HMWORKORDER') AND name = 'IX_HMWORKORDER_Assignee')
  CREATE INDEX IX_HMWORKORDER_Assignee ON dbo.HMWORKORDER(GECODEMP, AssignedToLogin, Status);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.HMWORKORDEREVENT') AND name = 'IX_HMWORKORDEREVENT_Timeline')
  CREATE INDEX IX_HMWORKORDEREVENT_Timeline ON dbo.HMWORKORDEREVENT(GECODEMP, WorkOrderId, OccurredAt);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.HMWORKORDERCOMMENT') AND name = 'IX_HMWORKORDERCOMMENT_Timeline')
  CREATE INDEX IX_HMWORKORDERCOMMENT_Timeline ON dbo.HMWORKORDERCOMMENT(GECODEMP, WorkOrderId, CreatedAt);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.HMWORKORDERATTACHMENT') AND name = 'IX_HMWORKORDERATTACHMENT_Order')
  CREATE INDEX IX_HMWORKORDERATTACHMENT_Order ON dbo.HMWORKORDERATTACHMENT(GECODEMP, WorkOrderId, CreatedAt);

COMMIT TRANSACTION;
