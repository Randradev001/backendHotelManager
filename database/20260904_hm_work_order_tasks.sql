USE HotelManagerDB;
GO
SET XACT_ABORT ON;
IF OBJECT_ID('dbo.HMWORKORDERTASK','U') IS NULL
BEGIN
  CREATE TABLE dbo.HMWORKORDERTASK(
    GECODEMP DECIMAL(10,0) NOT NULL,
    TaskId BIGINT IDENTITY(1,1) NOT NULL,
    WorkOrderId BIGINT NOT NULL,
    TaskDescription NVARCHAR(300) NOT NULL,
    TaskStatus VARCHAR(20) NOT NULL CONSTRAINT DF_HMWORKORDERTASK_Status DEFAULT('TODO'),
    ResponsibleLogin VARCHAR(10) NULL,
    SortOrder INT NOT NULL CONSTRAINT DF_HMWORKORDERTASK_Sort DEFAULT(0),
    CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMWORKORDERTASK_Created DEFAULT(SYSUTCDATETIME()),
    UpdatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_HMWORKORDERTASK_Updated DEFAULT(SYSUTCDATETIME()),
    CONSTRAINT PK_HMWORKORDERTASK PRIMARY KEY(GECODEMP,TaskId),
    CONSTRAINT FK_HMWORKORDERTASK_Order FOREIGN KEY(GECODEMP,WorkOrderId) REFERENCES dbo.HMWORKORDER(GECODEMP,WorkOrderId),
    CONSTRAINT CK_HMWORKORDERTASK_Status CHECK(TaskStatus IN('TODO','IN_PROGRESS','COMPLETED','CANCELLED'))
  );
  CREATE INDEX IX_HMWORKORDERTASK_Order ON dbo.HMWORKORDERTASK(GECODEMP,WorkOrderId,SortOrder,TaskId);
END;
GO
